-- SELECT CON DATOS DE VARIAS TABLAS
-- 1) Cada cliente con el nombre de su asesor
SELECT C.NOMBRE AS CLIENTE, E.NOMBRE AS ASESOR
FROM CLIENTE C
JOIN EMPLEADO E ON C.ID_EMPLEADO = E.ID_EMPLEADO;

-- 2) Cuentas de cada cliente con su saldo y último acceso
SELECT C.NOMBRE AS CLIENTE, CU.NUM_CUENTA, CU.SALDO, CC.FECHA AS ULTIMO_ACCESO
FROM CLIENTE C
JOIN CUENTA_CLIENTE CC ON C.ID_CLIENTE = CC.ID
JOIN CUENTA CU ON CC.NUM_CUENTA = CU.NUM_CUENTA;

-- 3) Préstamos con su sucursal y sus titulares
SELECT P.ID_P AS PRESTAMO, P.IMPORTE, P.NOMBRE_SUCURSAL, S.LOCALIDAD, C.NOMBRE AS TITULAR
FROM PRESTAMO P
JOIN SUCURSAL S ON P.NOMBRE_SUCURSAL = S.NOMBRE
JOIN CLIENTE_PRESTAMO CP ON P.ID_P = CP.ID_PRESTAMO
JOIN CLIENTE C ON CP.ID_CLIENTE = C.ID_CLIENTE;

-- 4) Cada empleado con el nombre de su jefe
SELECT E.NOMBRE AS EMPLEADO, J.NOMBRE AS JEFE
FROM EMPLEADO E
LEFT JOIN EMPLEADO J ON E.ID_JEFE = J.ID_EMPLEADO;

-- 5) Antigüedad de cada empleado en años (dato derivado)
SELECT NOMBRE, FECHA AS CONTRATACION,
       TIMESTAMPDIFF(YEAR, FECHA, CURDATE()) AS ANTIGUEDAD_ANIOS
FROM EMPLEADO;

